class Solution {
public:
    long long countCommas(long long n) {
        string s = to_string(n);
        if (s.length() < 4)
            return 0;
        if (n >= 1000 && n < 1000000)
            return n - 999;
        if (n >= 1000000LL && n < 1000000000LL)
            return 2 * (n - 1000000LL + 1) + 1000000 - 1000;
        if (n >= 1000000000LL && n < 1000000000000LL)
            return 3 * (n - 1000000000LL + 1) +
                   2 * (1000000000LL - 1 - 1000000LL + 1) + 1000000LL - 1000;
        if (n >= 1000000000000LL && n < 1000000000000000LL)
            return 4 * (n - 1000000000000LL + 1) +
                   3 * (1000000000000LL - 1 - 1000000000LL + 1) +
                   2 * (1000000000LL - 1 - 1000000LL + 1) + 1000000LL - 1000;
        if (n == 1000000000000000LL)
            return 5 + 4 * (1000000000000000LL - 1000000000000LL) +
                   3 * (1000000000000LL - 1 - 1000000000LL + 1) +
                   2 * (1000000000LL - 1 - 1000000LL + 1) + 1000000LL - 1000;
        return 0;
    }
};